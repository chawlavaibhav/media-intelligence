#!/usr/bin/env python3
"""CANON-V1 / C-C7 — generate SYNTHETIC verdict fixtures for the corrected gate.

Every file produced carries "dummy": true and a reviewer id that cannot be mistaken for a person.
These exist to prove the scoring logic behaves, never to stand in for a judgement. No fixture here
is evidence about Canon.

Run: python3 canon/experiments/v1/value-gate/make_dummy_verdicts.py
"""
from __future__ import annotations

import json
import pathlib
import random

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "dry-run"
DIMENSIONS = [
    "concept_quality", "hierarchy_reasoning", "proposition_clarity", "objective_fit",
    "audience_fit", "visual_temporal_strategy", "trade_off_awareness",
    "contradiction_handling", "appropriate_specificity",
]
OK = {"verdict": "preserved", "violations": []}


def load():
    man = json.loads((HERE / "run-manifest.json").read_text())
    key = {k["pair_id"]: k for k in json.loads((HERE / "blinding-key.json").read_text())["mapping"]}
    early = json.loads((HERE / "early-12-manifest.json").read_text())
    roles = {b["brief_id"]: b["gate_role"] for b in early["briefs"]}
    pairs = [(p["pair_id"], roles[p["brief_id"]]) for p in man["pairs"]]
    return pairs, key


def canon_letter(pid, key):
    return "A" if key[pid]["A"] == "oracle_canon" else "B"


def entry(pid, reviewer, letter, intent=None):
    """A verdict favouring `letter` on every dimension and overall."""
    return {
        "pair_id": pid, "reviewer_id": reviewer, "reviewed_at": "2026-08-26T00:00:00Z",
        "dimensions": {d: letter for d in DIMENSIONS},
        "explicit_intent_preservation": intent or {"A": dict(OK), "B": dict(OK)},
        "overall": letter,
        "reviewer_comment": "synthetic fixture",
    }


def write(name, rows, note, reviewers_required=2):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(json.dumps({
        "run_id": "CANON-V1-GATE-001", "dummy": True, "reviewers_required": reviewers_required,
        "note": "SYNTHETIC. Generated by make_dummy_verdicts.py to exercise the scoring pipeline. "
                "Contains no human judgement and is not evidence. " + note,
        "verdicts": rows,
    }, indent=2) + "\n")


def main() -> None:
    pairs, key = load()
    cov = [p for p, r in pairs if r == "coverage_probe"]
    gap = [p for p, r in pairs if r == "gap_probe"]

    def canon_wins_on(win_pairs, extra=None):
        rows = []
        for pid, _ in pairs:
            c = canon_letter(pid, key)
            other = "B" if c == "A" else "A"
            letter = c if pid in win_pairs else other
            for rv in ("DUMMY-R1", "DUMMY-R2"):
                rows.append(entry(pid, rv, letter))
        if extra:
            extra(rows)
        return rows

    # Coverage bands. Gap probes always lose here, to prove they do not rescue the band.
    write("coverage-5of7-continue.json", canon_wins_on(set(cov[:5])),
          "5 of 7 coverage probes unanimously won; all gap probes lost. Expect band=continue.")
    write("coverage-4of7-mixed.json", canon_wins_on(set(cov[:4])),
          "4 of 7 coverage probes won. Expect band=mixed.")
    write("coverage-3of7-stop.json", canon_wins_on(set(cov[:3])),
          "3 of 7 coverage probes won. Expect band=stop.")

    # Gap probes must not move the band: same 3/7 coverage, but every gap probe wins.
    write("gap-probes-do-not-rescue.json", canon_wins_on(set(cov[:3]) | set(gap)),
          "3 of 7 coverage probes won but ALL 5 gap probes won. Expect band=stop regardless.")
    # ...and gap losses must not drag a passing band down.
    write("gap-probes-do-not-sink.json", canon_wins_on(set(cov[:5])),
          "5 of 7 coverage won, 0 of 5 gap probes won. Expect band=continue regardless.")

    # Reviewer disagreement on one otherwise-winning coverage pair drops it to 4/7.
    rows = canon_wins_on(set(cov[:5]))
    flip = cov[0]
    for r in rows:
        if r["pair_id"] == flip and r["reviewer_id"] == "DUMMY-R2":
            other = "B" if canon_letter(flip, key) == "A" else "A"
            r["dimensions"] = {d: other for d in DIMENSIONS}
            r["overall"] = other
    write("reviewer-disagreement.json", rows,
          "5 coverage pairs would win, but reviewers disagree on one. Expect that pair NOT counted, "
          "4 of 7, band=mixed, and the pair listed under reviewer_disagreement_pairs.")

    # One reviewer only.
    write("single-reviewer.json", [r for r in canon_wins_on(set(cov[:5]))
                                   if r["reviewer_id"] == "DUMMY-R1"],
          "Only one reviewer per pair. Expect INCOMPLETE, exit 1.", reviewers_required=2)

    # Same reviewer twice.
    rows = canon_wins_on(set(cov[:5]))
    for r in rows:
        r["reviewer_id"] = "DUMMY-R1"
    write("duplicate-reviewer.json", rows,
          "Both verdicts on every pair come from one reviewer id. Expect INCOMPLETE, exit 1.")

    # Intent regression on a gap probe, with a passing coverage band, to prove it is global.
    def add_regression(rows):
        pid = gap[0]
        c = canon_letter(pid, key)
        g = "B" if c == "A" else "A"
        for r in rows:
            if r["pair_id"] == pid:
                r["explicit_intent_preservation"] = {
                    c: {"verdict": "violated",
                        "violations": [{"kind": "exact_string_altered",
                                        "detail": "synthetic fixture violation"}]},
                    g: dict(OK),
                }
    write("intent-regression-overrides.json", canon_wins_on(set(cov[:5]), add_regression),
          "5 of 7 coverage probes won (band would be continue) but Canon violated intent on a GAP "
          "probe. Expect headline=intent_regression and continuation blocked.")

    # Missing a pair entirely.
    rows = [r for r in canon_wins_on(set(cov[:5])) if r["pair_id"] != pairs[-1][0]]
    write("missing-pair.json", rows, "One pair has no verdicts at all. Expect INCOMPLETE, exit 1.")

    # A dimension left unjudged.
    rows = canon_wins_on(set(cov[:5]))
    del rows[0]["dimensions"][DIMENSIONS[2]]
    write("missing-dimension.json", rows, "One dimension unjudged. Expect INCOMPLETE, exit 1.")

    # Position bias only: every reviewer always picks A.
    rows = []
    for pid, _ in pairs:
        for rv in ("DUMMY-R1", "DUMMY-R2"):
            rows.append(entry(pid, rv, "A"))
    write("position-bias-always-A.json", rows,
          "Both reviewers always pick whichever plan is shown first. With balanced 6/6 blinding, "
          "Canon should win about half the pairs and must not reach the continue band.")

    print(json.dumps({"fixtures": sorted(p.name for p in OUT.glob('*.json')),
                      "coverage_pairs": cov, "gap_pairs": gap}, indent=2))


if __name__ == "__main__":
    main()

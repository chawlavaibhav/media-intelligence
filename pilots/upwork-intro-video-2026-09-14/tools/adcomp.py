def card(lines: list[tuple[str, str, int, str]], size=(1920, 1080), ground: str = "#F5F1EA",
         align: str = "left", margin: float = 0.09, gap: float = 0.35, valign: str = "center") -> Image.Image:
    """Solid-ground card. lines = [(text, font, size_px, colour), ...]. Left-aligned by default
    (design doc: centre only when line widths are within ~15%)."""
    W, H = size
    im = Image.new("RGBA", (W, H), _hex_to_rgba(ground))
    glyphs = [text(t, f, s, c) for (t, f, s, c) in lines]
    total = sum(g.height for g in glyphs) + sum(int(s * gap) for (_, _, s, _) in lines[:-1])
    y = (H - total) // 2 if valign == "center" else int(H * 0.12)
    m = int(W * margin)
    for g, (_, _, s, _) in zip(glyphs, lines):
        x = m if align == "left" else (W - g.width) // 2
        paste(im, g, x, y)
        y += g.height + int(s * gap)
    return im


